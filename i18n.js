  const sorted = pairs.sort((a, b) => b[0].length - a[0].length);
  // One pass, whole words, longest phrase first: a phrase only matches where it is not glued to
  // other letters (so "no" never matches inside "not"), and translated output is never re-scanned.
  const escapeRe = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const wordy = /[\p{L}\p{N}]/u;
  const compiled = {};
  const matcher = (language) => {
    if (compiled[language]) return compiled[language];
    const map = new Map(),
      alts = [];
    const list = sorted
      .filter(([es, en]) => es && en)
      .map(([es, en]) => (language === 'en' ? [es, en] : [en, es]))
      .sort((a, b) => b[0].length - a[0].length);
    for (const [src, to] of list) {
      if (map.has(src)) continue;
      map.set(src, to);
      const pre = wordy.test(src[0]) ? '(?<![\\p{L}\\p{N}])' : '',
        post = wordy.test(src[src.length - 1]) ? '(?![\\p{L}\\p{N}])' : '';
      alts.push(pre + escapeRe(src) + post);
    }
    return (compiled[language] = { re: new RegExp(alts.join('|'), 'gu'), map });
  };
  const swap = (text, language) => {
    if (language !== 'en' && language !== 'es') return text;
    const { re, map } = matcher(language);
    return String(text).replace(re, (m) => (map.has(m) ? map.get(m) : m));
  };
  function apply(root, language) {
    if (!root) return;
    document.documentElement.lang = language;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) {
      const n = walker.currentNode;
      // External content (news titles, company names, research text) is marked data-no-i18n and
      // must never be rewritten by the substring translator.
      if (n.parentElement?.closest('script,style,code,pre,textarea,[data-no-i18n]')) continue;
      if (n.nodeValue.trim()) nodes.push(n);
    }
    for (const n of nodes) {
      const translated = swap(n.nodeValue, language);
      if (translated !== n.nodeValue) n.nodeValue = translated;
    }
    for (const el of root.querySelectorAll(
      'input[placeholder],textarea[placeholder],button[title],[aria-label]',
    )) {
      if (el.closest('[data-no-i18n]')) continue;
      for (const attr of ['placeholder', 'title', 'aria-label']) {
        const v = el.getAttribute(attr);
        if (v) {
          const t = swap(v, language);
          if (t !== v) el.setAttribute(attr, t);
        }
      }
    }
  }
  const API = { apply, swap, pairs };
  if (typeof window !== 'undefined') window.PMI18n = API;
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
